_MARKDOWN_ESCAPE_RE = re.compile(r"\\([_*#\[\]()`.>~|-])")


def literal_text(text: str) -> str:
    """
        Makes free text from an OpenAPI description safe inside a generated string
        literal or docstring.

        Descriptions arrive as markdown, where a backslash escapes punctuation such
        as ``\\_``. Python reads the same sequence as an invalid escape and warns at
        import time, and a real backslash would change the literal's value. Markdown
        escapes are unwrapped and any remaining backslash is doubled.

        :param text: The description text.

        :returns: Text that can be written verbatim inside a generated literal.
    """
    rtnval = _MARKDOWN_ESCAPE_RE.sub(r"\1", text or "")
    rtnval = rtnval.replace("\\", "\\\\")
    return rtnval


@dataclass
class ParameterSpec:
    """
        Specification for a parameter from the OpenAPI description.
    """
    name: str
    location: str
    required: bool
    schema: Dict[str, Any]
    description: str


@dataclass
class OperationSpec:
    """
        Container holding details about an API operation.
    """
    path: str
    http_method: str
    group: str
    operation_id: str
    method_name: str
    summary: str
    description: str
    parameters: List[ParameterSpec]
    request_body: Optional[Dict[str, Any]]
    responses: Dict[str, Any]
    external_docs: Optional[Dict[str, Any]] = None
    response_schema_info: Optional[Dict[str, Any]] = None  # Extracted 200 response schema info
    archetype: Optional[str] = None


@dataclass
class TypeSpec:
    """
        Specification for a generated type.
    """
    name: str
    schema: Dict[str, Any]
    description: str = ""
    source: str = ""  # 'parameter', 'schema', 'request_body'


class RestClientGenerator:
    """
        Shapes the patterns for the REST API generation.
    """

    REST_CLIENT_BASE_CLASS: Type[RestClientBase] = RestClientBase
    GROUP_BASE_TYPE: Type[RestApiGroup] = RestApiGroup
    SCHEMA_BASE_TYPE: Type[SchemaObject] = SchemaObject
    SCHEMA_FIELD_TYPE: Type[Field] = Field
    ASPECTS_TYPE: Type[AspectsRest] = AspectsRest
    PAGEDLIST_TYPE: Type[PagedList] = PagedList

    SCHEMA_MODULE_ROOT = "ccai.github.rest.clients.public.schemas"
    GROUP_MODULE_ROOT = "ccai.github.rest.clients.public.groups"
    CLIENT_MODULE_ROOT = "ccai.github.rest.clients.public"


    DEFAULT_PAGINATION_DETECTION_HINTS = {
        "detection_rules": {
            "query_parameters": {
                "parameters": ["page", "per_page"],
                "enabled": True
            }
        },
        "default_parameters": {
            "page_param": "page",
            "per_page_param": "per_page"
        }
    }

    def __init__(self, openapi_spec_file: str, clients_root: str, client_class_name: str = "GithubRestClient"):
        self._spec_path = Path(openapi_spec_file).resolve()
        self._clients_root = Path(clients_root).resolve()
        self._client_class_name = client_class_name
        self._spec = self._load_openapi_spec(self._spec_path)

        self._components = self._spec.get("components", {})
        self._tag_catalog: Dict[str, str] = {}
        self._groups: Dict[str, List[OperationSpec]] = {}
        
        # Type registries for the new type-based approach
        self._common_types: Dict[str, TypeSpec] = {}  # Common parameter types
        self._schema_types: Dict[str, TypeSpec] = {}  # Schema types from components
        self._request_types: Dict[str, TypeSpec] = {}  # Request body types
        
        # Schema usage tracking for file organization
        self._schema_usage: Dict[str, Dict[str, Any]] = {}  # schema_name -> {tags, creating_ops, using_ops}
        
        # Schema import lookup table: type_name -> import statement
        self._schema_imports: Dict[str, str] = {}  # TypeName -> f"from {SCHEMA_MODULE_ROOT}.file import TypeName"
        
        # Load pagination hints
        self._pagination_hints = self.DEFAULT_PAGINATION_DETECTION_HINTS
        
        # Load API hints
        self._api_hints = self._load_api_hints()

        self._build_type_registries()
        self._process_spec()
        self._analyze_schema_usage()
        return

    def generate(self):
        """
            Generate all client, group, and schema modules.
        """
        clients_root = self._clients_root
        groups_dir = clients_root / "groups"
        schemas_dir = clients_root / "schemas"

        for directory in (groups_dir, schemas_dir):
            directory.mkdir(parents=True, exist_ok=True)

        # Generate schema modules first
        self._generate_schema_modules(schemas_dir)

        sorted_groups = sorted(self._groups.keys())

        for group in sorted_groups:
            ops = sorted(self._groups[group], key=lambda o: self._safe_snake(o.method_name))
            self._generate_group_module(group, ops, groups_dir)

        self._generate_client_module(sorted_groups, clients_root)
        self._write_simple_init(groups_dir)
        self._write_schemas_init(schemas_dir)
        self._write_simple_init(clients_root)
        return

    def _analyze_schema_usage(self):
        """
            Analyze which schemas are used by which operations and tags.
            This information is used to organize schemas into appropriate files.
        """
        for path_leaf, method_catalog in self._spec["paths"].items():
            for call_method, op_desc in method_catalog.items():
                if call_method not in SUPPORTED_HTTP_METHODS:
                    continue
                
                operation_id = op_desc.get("operationId", "")
                tags = op_desc.get("tags", [])
                tag = tags[0] if tags else "default"
                
                # Extract schema references from responses
                responses = op_desc.get("responses", {})
                response_200 = responses.get("200", {})
                content = response_200.get("content", {})
                json_content = content.get("application/json", {})
                schema = json_content.get("schema", {})
                
                # Extract schema references from request body
                request_body = op_desc.get("requestBody", {})
                
                # Recursively extract all schema references
                refs = set()
                self._extract_schema_refs(schema, refs)
                self._extract_schema_refs(request_body, refs)
                
                for ref_name in refs:
                    if ref_name not in self._schema_usage:
                        self._schema_usage[ref_name] = {
                            'tags': set(),
                            'creating_ops': [],
                            'using_ops': []
                        }
                    
                    self._schema_usage[ref_name]['tags'].add(tag)
                    self._schema_usage[ref_name]['using_ops'].append(operation_id)
                    
                    # Check if this is a creating operation (POST/PUT/PATCH)
                    if call_method.upper() in ['POST', 'PUT', 'PATCH']:
                        self._schema_usage[ref_name]['creating_ops'].append(operation_id)
        return
    
    def _build_schema_import_table(self):
        """
            Build lookup table of import statements for all schema types.
            Maps TypeName -> "from ccai.github.rest.clients.public.schemas.file import TypeName"
        """
        for schema_name, type_spec in self._schema_types.items():
            file_name = self._determine_schema_file(schema_name)
            type_name = type_spec.name
            import_stmt = f"from {self.SCHEMA_MODULE_ROOT}.{file_name} import {type_name}"
            self._schema_imports[type_name] = import_stmt
        return

    def _build_type_registries(self):
        """
            Build type registries from components.
        """
        components = self._components
        
        # Build common parameter types from components.parameters
        comp_params = components.get("parameters", {})
        for param_name, param_def in comp_params.items():
            type_name = self._safe_pascal(param_name)
            self._common_types[param_name] = TypeSpec(
                name=type_name,
                schema=param_def.get("schema", {}),
                description=param_def.get("description", ""),
                source="parameter"
            )
        
        # Build schema types from components.schemas
        comp_schemas = components.get("schemas", {})
        for schema_name, schema_def in comp_schemas.items():
            type_name = self._safe_pascal(schema_name)
            self._schema_types[schema_name] = TypeSpec(
                name=type_name,
                schema=schema_def,
                description=schema_def.get("description", ""),
                source="schema"
            )
        return

    def _collect_parameters(self, path_level_params: List[dict], op_level_params: List[dict]) -> List[ParameterSpec]:
        parameters: List[ParameterSpec] = []
        for pentry in path_level_params + op_level_params:
            param_def = self._dereference_parameter(pentry)
            name = param_def.get("name", "unnamed")
            location = param_def.get("in", "query")
            required = bool(param_def.get("required", False))
            schema = param_def.get("schema", {})
            description = param_def.get("description", "")
            parameters.append(
                ParameterSpec(
                    name=name,
                    location=location,
                    required=required,
                    schema=schema,
                    description=description,
                )
            )
        return parameters

    def _collect_schema_types_from_properties(self, schema: Dict[str, Any], types_set: set):
        """
            Collect schema types referenced by properties for class field definitions.
        """
        if not schema:
            return

        properties = schema.get("properties", {})
        for prop_schema in properties.values():
            self._collect_schema_types_from_schema(prop_schema, types_set)
        return

    def _collect_schema_types_from_schema(self, schema: Dict[str, Any], types_set: set, refs_seen: Optional[set] = None):
        """
            Recursively collect all schema type names referenced in a schema.
        """
        if not schema:
            return

        if refs_seen is None:
            refs_seen = set()
        
        # Check for direct $ref
        if "$ref" in schema:
            ref = schema["$ref"]
            if ref.startswith("#/components/schemas/"):
                schema_name = ref.split("/")[-1]
                if schema_name in refs_seen:
                    return
                refs_seen.add(schema_name)
                type_spec = self._schema_types.get(schema_name)
                if type_spec:
                    if self._schema_can_generate_class(type_spec.schema):
                        types_set.add(type_spec.name)
                    else:
                        self._collect_schema_types_from_schema(type_spec.schema, types_set, refs_seen)
            return
        
        if "oneOf" in schema or "anyOf" in schema:
            variants = schema.get("oneOf") or schema.get("anyOf") or []
            for sub_schema in variants:
                self._collect_schema_types_from_schema(sub_schema, types_set, refs_seen)
            return

        # Check for array items
        if schema.get("type") == "array" and "items" in schema:
            self._collect_schema_types_from_schema(schema["items"], types_set, refs_seen)
            return

        # Objects are represented as Dict[str, Any] in type annotations.
        if schema.get("type") == "object":
            return
        
        return

    def _dereference_parameter(self, param_entry: dict) -> dict:
        if "$ref" in param_entry:
            ref_path = param_entry["$ref"]
            resolved = self._resolve_ref(ref_path)
            if not isinstance(resolved, dict):
                errmsg = f"Reference '{ref_path}' did not resolve to a parameter dictionary."
                raise ValueError(errmsg)
            return resolved
        return param_entry

    def _derive_group_and_method(self, operation_id: str, tags: List[str], path: str, http_method: str) -> Tuple[str, str]:
        """
            Derive the group name and method name for an API operation.
            
            Priority:
            1. Check api-hints.json for method-name override
            2. Use operationId (strip group prefix if present)
            3. Fall back to http_method
        """
        # Check for hints override
        method_hints = self._get_api_method_hints(path, http_method)
        if "operationId" in method_hints:
            operation_id = method_hints["operationId"]

        if "method-name" in method_hints:
            method_name = method_hints["method-name"]
            group_name = tags[0] if tags else "default"
            group_name = self._safe_snake(group_name)
            method_name = self._safe_snake(method_name)
            return group_name, method_name
        
        # Use operationId to derive group and method
        group_name = tags[0] if tags else "default"
        method_name = operation_id

        if operation_id and "/" in operation_id:
            parts = operation_id.split("/", 1)
            group_name = parts[0]
            method_name = parts[1]
        elif not tags and operation_id:
            group_name = operation_id
            method_name = operation_id
        elif not operation_id:
            # Fallback to http_method if no operationId
            method_name = http_method

        group_name = self._safe_snake(group_name)
        method_name = self._safe_snake(method_name)
        return group_name, method_name

    def _detect_api_archetype(self, path: str, http_method: str, operation_id: str, op_desc: Dict[str, Any],
                             parameters: List[ParameterSpec], response_schema_info: Optional[Dict[str, Any]]) -> Optional[str]:
        """
            Detect the archetype for a specific API operation.

            :param path: API path.
            :param http_method: HTTP method name.
            :param operation_id: Operation id from the spec.
            :param op_desc: OpenAPI operation description.
            :param parameters: List of parameters for the operation.
            :param response_schema_info: Parsed response schema info.

            :returns: Detected archetype or None.
        """
        archetype = op_desc.get("archetype") or op_desc.get("x-archetype")
        archetype = self._normalize_archetype(archetype)
        if archetype:
            return archetype

        method_hints = self._get_api_method_hints(path, http_method)
        archetype = self._normalize_archetype(method_hints.get("archetype"))
        if archetype:
            return archetype

        archetype = self._detect_internal_archetype(path, http_method, operation_id, op_desc, parameters, response_schema_info)
        return archetype
    
    def _detect_internal_archetype(self, path: str, http_method: str, operation_id: str, op_desc: Dict[str, Any],
                                   parameters: List[ParameterSpec], response_schema_info: Optional[Dict[str, Any]]) -> Optional[str]:
        method = http_method.lower()
        path_lower = path.lower()
        summary = (op_desc.get("summary") or "").lower()
        description = (op_desc.get("description") or "").lower()
        opid = (operation_id or "").lower()
        combined = " ".join([summary, description, opid])

        if method in ("get", "head"):
            if "properties" in path_lower or "settings" in path_lower:
                return "get-properties"
            if response_schema_info and response_schema_info.get("type") == "list":
                if self._has_pagination_parameters(parameters):
                    return "paged-collection"
                return "collection"

        if method == "delete":
            return "delete-item"

        if method in ("put", "patch"):
            if "properties" in path_lower or "settings" in path_lower:
                return "set-properties"
            if "update" in combined or "set" in combined:
                return "update-item"
            return "action"

        if method == "post":
            if any(keyword in combined for keyword in ("create", "add", "provision")):
                return "create-item"
            return "action"

        return None

    def _determine_return_type(self, op: OperationSpec) -> str:
        """
            Determine the return type for the method.
        """
        schema_info = op.response_schema_info
        
        if not schema_info:
            return "Any"
        
        if schema_info.get("type") == "list":
            item_schema = schema_info.get("item_schema", {})
            item_type = self._schema_to_type(item_schema)
            
            # Check if paginated
            if self._is_paginated_operation(op):
                pagedlist_type_name = self.PAGEDLIST_TYPE.__name__
                return f"{pagedlist_type_name}[{item_type}]"
            else:
                return f"List[{item_type}]"
        
        elif schema_info.get("type") == "single":
            schema = schema_info.get("schema", {})
            return self._schema_to_type(schema)
        
        return "Any"

    def _determine_schema_file(self, schema_name: str) -> str:
        """
            Determine which file a schema should be placed in.
            Priority:
            1. Tag group the schema belongs to (if only one tag)
            2. Tag group of the API that creates the object (POST/PUT/PATCH operations)
            3. Use the classname in all lower case
        """
        usage = self._schema_usage.get(schema_name, {})
        tags = usage.get('tags', set())
        creating_ops = usage.get('creating_ops', [])
        
        # Priority 1: Single tag group
        if len(tags) == 1:
            return self._file_slug(list(tags)[0])
        
        # Priority 2: Tag from first creating operation
        if creating_ops:
            first_creating_op = creating_ops[0]
            # Extract tag from operation_id (format: "tag/method")
            if '/' in first_creating_op:
                tag = first_creating_op.split('/', 1)[0]
                return self._file_slug(tag)
        
        # Priority 3: Use schema classname in lowercase
        type_spec = self._schema_types.get(schema_name)
        if type_spec:
            return type_spec.name.lower()
        
        # Fallback
        return schema_name.lower()

    def _expected_status_codes(self, responses: Dict[str, Any]) -> List[int]:
        expected: List[int] = []
        for code_str in sorted(responses.keys()):
            if code_str.isdigit():
                code_int = int(code_str)
                if 200 <= code_int < 300:
                    expected.append(code_int)
        if not expected:
            expected.append(200)
        return expected

    def _extract_response_schema_info(self, responses: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        """
            Extract schema information from the 200 response.
            
            :returns: Dictionary with 'type' ('single' or 'list'), 'schema' (the schema dict),
                      and 'item_type' (for lists)
        """
        # Look for 200 response
        response_200 = responses.get("200")
        if not response_200:
            return None
        
        content = response_200.get("content", {})
        json_content = content.get("application/json")
        if not json_content:
            return None
        
        schema = json_content.get("schema", {})
        if not schema:
            return None
        
        # Determine if it's a list or single object
        schema_type = schema.get("type")
        
        if schema_type == "array":
            items_schema = schema.get("items", {})
            return {
                "type": "list",
                "schema": schema,
                "item_schema": items_schema
            }
        else:
            return {
                "type": "single",
                "schema": schema
            }
    
    def _extract_request_body_schema(self, request_body: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        """
            Extract schema from request body.
        """
        content = request_body.get("content", {})
        json_content = content.get("application/json")
        if json_content:
            return json_content.get("schema")
        return None

    def _extract_schema_refs(self, obj: Any, refs_set: set):
        """
            Recursively extract schema references from an object.
        """
        if isinstance(obj, dict):
            if '$ref' in obj:
                ref = obj['$ref']
                if ref.startswith('#/components/schemas/'):
                    schema_name = ref.split('/')[-1]
                    refs_set.add(schema_name)
            for value in obj.values():
                self._extract_schema_refs(value, refs_set)
        elif isinstance(obj, list):
            for item in obj:
                self._extract_schema_refs(item, refs_set)
        return

    def _field_default_literal(self, schema: Dict[str, Any], required: bool) -> str:
        if required:
            return ""

        if "default" in schema:
            dval = schema["default"]
            if isinstance(dval, str):
                return f'"{dval}"'
            return str(dval)

        return "None"

    def _file_slug(self, name: str) -> str:
        """
            Creates a filesystem-friendly slug without underscores.
        """
        slug = self._safe_snake(name).replace("_", "")
        if slug == "":
            slug = "generated"
        if slug[0].isdigit():
            slug = f"op{slug}"
        return slug

    def _generate_client_module(self, sorted_groups: List[str], clients_root: Path):
        client_filename = f"{self._client_class_name.lower()}.py"
        client_file = clients_root / client_filename
        lines: List[str] = [AUTO_GENERATED_BANNER]
        typing_imports = ["from typing import Optional"]
        module_imports = ["import weakref"]
        native_from_imports: List[str] = []
        third_party_imports: List[str] = []
        local_imports = [
            self._import_statement_for_type(self.ASPECTS_TYPE, ["DEFAULT_REST_ASPECTS"]),
            self._import_statement_for_type(self.REST_CLIENT_BASE_CLASS),
            "from ccai.credentials.basecredential import BaseCredential",
        ]

        for group in sorted_groups:
            gclass = f"{self._safe_pascal(group)}ApiGroup"
            gmodule = f"{self.GROUP_MODULE_ROOT}.{self._file_slug(group)}"
            local_imports.append(f"from {gmodule} import {gclass}")

        lines.extend(self._format_import_sections([
            typing_imports,
            module_imports,
            native_from_imports,
            third_party_imports,
            local_imports,
        ]))
        lines.append("")
        lines.append("")
        base_class_name = self.REST_CLIENT_BASE_CLASS.__name__
        lines.append(f"class {self._client_class_name}({base_class_name}):")
        lines.append('    """')
        lines.append("        GitHub public REST API client generated from the OpenAPI specification.")
        lines.append("    \"\"\"")
        aspects_type_name = self.ASPECTS_TYPE.__name__
        lines.append(f"    def __init__(self, host: str, credential: BaseCredential, port: Optional[int] = None, scheme: Optional[str] = \"https\", aspects: {aspects_type_name} = DEFAULT_REST_ASPECTS):")
        lines.append("        super().__init__(host, credential, port, scheme=scheme, aspects=aspects)")

        for group in sorted_groups:
            gclass = f"{self._safe_pascal(group)}ApiGroup"
            attr_name = f"_grp_{self._safe_snake(group)}"
            lines.append(f"        self.{attr_name} = {gclass}(self)")
        lines.append("        return")
        lines.append("")

        for group in sorted_groups:
            gclass = f"{self._safe_pascal(group)}ApiGroup"
            attr_name = f"_grp_{self._safe_snake(group)}"
            prop_name = self._safe_snake(group)
            lines.append("    @property")
            lines.append(f"    def {prop_name}(self) -> {gclass}:")
            lines.append(f"        return self.{attr_name}")
            lines.append("")

        content = "\n".join(lines).rstrip() + "\n"
        self._write_file(client_file, content)
        return

    def _generate_group_module(self, group: str, ops: List[OperationSpec], groups_dir: Path):
        """
            Generate API group module with Pythonic method signatures.
        """
        slug = self._file_slug(group)
        class_name = f"{self._safe_pascal(group)}ApiGroup"
        
        # Collect all schema types used in this group module
        used_types = set()
        for op in ops:
            # Collect from response schemas
            schema_info = op.response_schema_info
            if schema_info:
                if schema_info.get("type") == "list":
                    item_schema = schema_info.get("item_schema", {})
                    self._collect_schema_types_from_schema(item_schema, used_types)
                elif schema_info.get("type") == "single":
                    schema = schema_info.get("schema", {})
                    self._collect_schema_types_from_schema(schema, used_types)
            
            # Collect from request body
            if op.request_body:
                body_schema = self._extract_request_body_schema(op.request_body)
                if body_schema:
                    self._collect_schema_types_from_schema(body_schema, used_types)
        
        # Generate imports
        module_lines: List[str] = [AUTO_GENERATED_BANNER]
        typing_imports = ["from typing import Any, Dict, List, Optional, Union"]
        module_imports: List[str] = []
        native_from_imports: List[str] = []
        third_party_imports: List[str] = []
        local_imports = [
            self._import_statement_for_type(self.ASPECTS_TYPE, ["DEFAULT_REST_ASPECTS"]),
            self._import_statement_for_type(self.GROUP_BASE_TYPE),
            self._import_statement_for_type(self.PAGEDLIST_TYPE),
        ]
        
        # Add specific schema imports
        if used_types:
            for type_name in sorted(used_types):
                if type_name in self._schema_imports:
                    local_imports.append(self._schema_imports[type_name])
        
        module_lines.extend(self._format_import_sections([
            typing_imports,
            module_imports,
            native_from_imports,
            third_party_imports,
            local_imports,
        ]))
        module_lines.append("")
        module_lines.append("")
        group_base_name = self.GROUP_BASE_TYPE.__name__
        module_lines.append(f"class {class_name}({group_base_name}):")
        tag_desc = self._tag_catalog.get(group, "")
        if tag_desc:
            module_lines.append("    \"\"\"")
            module_lines.append(f"        {literal_text(tag_desc)}")
            module_lines.append("    \"\"\"")

        for op in ops:
            method_lines = self._generate_method_signature_and_body(op, group)
            module_lines.extend(method_lines)

        content = "\n".join(module_lines).rstrip() + "\n"
        out_path = groups_dir / f"{slug}.py"
        self._write_file(out_path, content)
        return
    
    def _generate_method_body(self, op: OperationSpec, path_params: List[ParameterSpec], 
                               query_params: List[ParameterSpec], header_params: List[ParameterSpec],
                               has_body: bool) -> List[str]:
        """
            Generate the method body that makes the HTTP call.
        """
        lines: List[str] = []
        
        # Get client reference and check aspects
        lines.append("        client = self.client")
        lines.append("        if aspects is None:")
        lines.append("            aspects = client.aspects")
        lines.append("")
        lines.append("        header_params = client.headers")
        lines.append("        if headers is not None:")
        lines.append("            header_params = headers")
        lines.append("")
        
        # Build path
        if path_params:
            lines.append(f"        leaf_template = \"{op.path}\"")
            lines.append("        path_params = {")
            for param in path_params:
                param_name = self._safe_snake(param.name)
                lines.append(f"            '{param.name}': {param_name},")
            lines.append("        }")
            lines.append("        call_leaf = leaf_template.format(**path_params)")
        else:
            lines.append(f"        call_leaf = \"{op.path}\"")
        lines.append("")
        
        # Build query params
        if query_params:
            lines.append("        query_params = {}")
            for param in query_params:
                param_name = self._safe_snake(param.name)
                lines.append(f"        if {param_name} is not None:")
                lines.append(f"            query_params['{param.name}'] = {param_name}")
        else:
            lines.append("        query_params = None")
        lines.append("")
        
        # Build header params
        if header_params:
            lines.append("        if header_params is None:")
            lines.append("            header_params = {}")
            for param in header_params:
                param_name = self._safe_snake(param.name)
                lines.append(f"        if {param_name} is not None:")
                lines.append(f"            header_params['{param.name}'] = {param_name}")
        lines.append("")
        
        # Make the call
        default_exp_status = self._expected_status_codes(op.responses)
        lines.append(f"        if exp_status is None:")
        lines.append(f"            exp_status = {default_exp_status}")
        lines.append("")
        lines.append("        resp = client.perform_call(")
        lines.append("            leaf=call_leaf,")
        lines.append(f"            method=\"{op.http_method}\",")
        lines.append("            params=query_params if query_params else None,")
        if has_body:
            lines.append("            body=body,")
        else:
            lines.append("            body=None,")
        lines.append("            exp_status=exp_status,")
        lines.append("            headers=header_params if header_params else None,")
        lines.append("            context_msg=None,")
        lines.append("            aspects=aspects,")
        lines.append("        )")
        
        # Parse and return response
        lines.extend(self._generate_response_parsing(op))
        
        return lines
    
    def _generate_method_signature_and_body(self, op: OperationSpec, group: str) -> List[str]:
        """
            Generate a single API method with Pythonic signature.
            
            Signature order:
            1. Required path parameters (positional)
            2. Request body with schema type (positional, if present)
            3. Mandatory query/header parameters (positional)
            4. * (keyword-only marker)
            5. Optional query/header parameters (kwargs)
            6. aspects parameter (framework, last)
        """
        lines: List[str] = []
        method_name = self._safe_snake(op.method_name)
        
        # Build signature parts
        sig_params: List[str] = ["self"]
        
        # Collect parameters by type
        path_params = [p for p in op.parameters if p.location == "path"]
        query_params = [p for p in op.parameters if p.location == "query"]
        header_params = [p for p in op.parameters if p.location == "header"]
        
        # 1. Required path parameters (always first)
        for param in path_params:
            param_name = self._safe_snake(param.name)
            param_type = self._schema_to_type(param.schema)
            sig_params.append(f"{param_name}: {param_type}")
        
        # 2. Request body with actual schema type
        body_type_str = None
        if op.request_body:
            body_schema = self._extract_request_body_schema(op.request_body)
            if body_schema:
                body_type_str = self._schema_to_type(body_schema)
                sig_params.append(f"body: {body_type_str}")
        
        # 3. Mandatory (required) query/header parameters
        mandatory_qh_params = [p for p in query_params + header_params if p.required]
        for param in mandatory_qh_params:
            param_name = self._safe_snake(param.name)
            param_type = self._schema_to_type(param.schema)
            sig_params.append(f"{param_name}: {param_type}")
        
        # 4. Mark start of keyword-only parameters
        sig_params.append("*")
        
        # 5. Optional query/header parameters
        optional_qh_params = [p for p in query_params + header_params if not p.required]
        for param in optional_qh_params:
            param_name = self._safe_snake(param.name)
            param_type = self._schema_to_type(param.schema)
            default = self._field_default_literal(param.schema, False) or "None"
            sig_params.append(f"{param_name}: Optional[{param_type}] = {default}")
        
        # 6. Framework parameters (optional)
        sig_params.append("exp_status: Optional[List[int]] = None")
        sig_params.append("headers: Optional[Dict[str, str]] = None")
        aspects_type_name = self.ASPECTS_TYPE.__name__
        sig_params.append(f"aspects: Optional[{aspects_type_name}] = None")
        
        # Determine return type
        return_type = self._determine_return_type(op)
        
        # Generate method signature
        lines.append("")
        sig_line = f"    def {method_name}({', '.join(sig_params)}) -> {return_type}:"
        lines.append(sig_line)
        lines.append("        \"\"\"")
        if op.summary:
            lines.append(f"            {literal_text(op.summary)}")
        if op.description and op.description != op.summary:
            lines.append(f"            ")
            lines.append(f"            {literal_text(op.description)}")
        lines.append("        \"\"\"")
        
        # Generate method body
        lines.extend(self._generate_method_body(op, path_params, query_params, header_params, body_type_str is not None))
        
        return lines

    def _generate_response_parsing(self, op: OperationSpec) -> List[str]:
        """
            Generate code to parse the response and return the appropriate type.
        """
        lines: List[str] = []
        schema_info = op.response_schema_info

        # A success status can legitimately carry no content (204/205, or an empty
        # 202 "Accepted"). Guard resp.json() so those return None instead of raising
        # on an empty body; any other status still parses, so an unexpected-empty 200
        # surfaces as an error rather than being silently masked.
        no_content_guard = "resp.status_code in (204, 205) or (resp.status_code == 202 and len(resp.content) == 0)"

        if not schema_info:
            lines.append(f"        if {no_content_guard}:")
            lines.append("            rtnval = None")
            lines.append("        else:")
            lines.append("            rtnval = resp.json()")
            lines.append("        return rtnval")
            return lines

        if schema_info.get("type") == "list":
            item_schema = schema_info.get("item_schema", {})
            item_type = self._schema_to_type(item_schema)

            lines.append("        raw_data = resp.json()")
            lines.append(f"        items = [self._parse_item(item, {item_type}) for item in raw_data]")

            if self._is_paginated_operation(op):
                pagedlist_type_name = self.PAGEDLIST_TYPE.__name__
                lines.append(f"        rtnval = {pagedlist_type_name}[{item_type}](items, dict(resp.headers), raw_data)")
                lines.append("        return rtnval")
            else:
                lines.append("        return items")

        elif schema_info.get("type") == "single":
            schema = schema_info.get("schema", {})
            data_type = self._schema_to_type(schema)

            # Check if this is a custom SchemaObject type (has $ref) or primitive
            if "$ref" in schema:
                # Custom type with from_dict method
                lines.append(f"        if {no_content_guard}:")
                lines.append("            rtnobj = None")
                lines.append("        else:")
                lines.append("            raw_data = resp.json()")
                lines.append(f"            rtnobj = {data_type}.from_dict(raw_data)")
                lines.append("        return rtnobj")
            else:
                # Primitive type or Dict[str, Any] - return directly or use _parse_item
                lines.append(f"        if {no_content_guard}:")
                lines.append("            rtnval = None")
                lines.append("        else:")
                lines.append("            raw_data = resp.json()")
                lines.append(f"            rtnval = self._parse_item(raw_data, {data_type})")
                lines.append("        return rtnval")

        return lines

    def _generate_schema_modules(self, schemas_dir: Path):
        """
            Generate schema modules organized by tag/operation.
        """
        # Group schemas by their target file
        schemas_by_file: Dict[str, List[Tuple[str, TypeSpec]]] = {}

        self._schema_imports.clear()
        
        for schema_name, type_spec in self._schema_types.items():
            file_name = self._determine_schema_file(schema_name)
            if file_name not in schemas_by_file:
                schemas_by_file[file_name] = []
            schemas_by_file[file_name].append((schema_name, type_spec))
            import_stmt = f"from {self.SCHEMA_MODULE_ROOT}.{file_name} import {type_spec.name}"
            self._schema_imports[type_spec.name] = import_stmt
        
        # Generate each schema file
        for file_name, schemas in sorted(schemas_by_file.items()):
            emit_schemas: List[Tuple[str, TypeSpec]] = []
            class_lines_by_type: Dict[str, List[str]] = {}

            for schema_name, type_spec in schemas:
                class_lines = self._generate_type_class(type_spec)
                if class_lines:
                    emit_schemas.append((schema_name, type_spec))
                    class_lines_by_type[type_spec.name] = class_lines

            out_path = schemas_dir / f"{file_name}.py"
            if not emit_schemas:
                if out_path.exists():
                    out_path.unlink()
                continue

            module_lines: List[str] = [AUTO_GENERATED_BANNER]
            module_lines.append("from __future__ import annotations")
            module_lines.append("")
            typing_imports = ["from typing import Any, Dict, List, Optional, Union"]
            module_imports: List[str] = []
            native_from_imports: List[str] = []
            third_party_imports: List[str] = []
            local_imports = [
                self._import_statement_for_type(self.SCHEMA_BASE_TYPE),
                self._import_statement_for_type(self.SCHEMA_FIELD_TYPE),
            ]
            module_lines.extend(self._format_import_sections([
                typing_imports,
                module_imports,
                native_from_imports,
                third_party_imports,
                local_imports,
            ]))
            module_lines.append("")
            module_lines.append("")
            
            # Generate schema classes for this file
            ordered_schemas = self._order_schema_definitions(emit_schemas)
            for schema_name, type_spec in ordered_schemas:
                class_lines = class_lines_by_type.get(type_spec.name, [])
                if not class_lines:
                    continue
                module_lines.extend(class_lines)
                module_lines.append("")
                module_lines.append("")
            
            content = "\n".join(module_lines).rstrip() + "\n"
            self._write_file(out_path, content)
        return

    def _generate_type_class(self, type_spec: TypeSpec) -> List[str]:
        """
            Generate a class that inherits from SchemaObject using Field descriptors.
        """
        lines: List[str] = []
        schema = type_spec.schema
        
        # Handle simple types (parameters) - skip generation
        if not self._schema_can_generate_class(schema):
            return lines
        
        properties = schema.get("properties", {})
        required_fields = schema.get("required", [])
        
        # Generate class definition
        schema_base_name = self.SCHEMA_BASE_TYPE.__name__
        lines.append(f"class {type_spec.name}({schema_base_name}):")
        
        # Docstring
        if type_spec.description:
            lines.append('    """')
            lines.append(f"        {literal_text(type_spec.description)}")
            lines.append('    """')
        
        # Generate Field descriptors for each property
        for field_name, prop_schema in properties.items():
            attr_name = self._safe_snake(field_name)
            field_type_str = self._schema_to_type(prop_schema, use_forward_refs=True)
            is_required = field_name in required_fields
            description = prop_schema.get("description", "")
            
            # Escape description for string literal
            if description:
                description = literal_text(description).replace('"', '\\"').replace('\n', ' ').replace('\r', '')
            
            # Build Field() call
            field_parts = [field_type_str]
            if is_required:
                field_parts.append("required=True")
            if description:
                field_parts.append(f'description="{description}"')
            
            field_def = f"    {attr_name} = Field({', '.join(field_parts)})"
            lines.append(field_def)
        
        return lines

    def _get_api_method_hints(self, path: str, http_method: str) -> Dict[str, Any]:
        """
            Get API hints for a specific path and method.

            :param path: The API path.
            :param http_method: The HTTP method.

            :returns: Dictionary of hints for the API method.
        """
        path_hints = self._api_hints.get("paths", {}).get(path, {})
        method_hints = path_hints.get(http_method.lower(), {}) or {}
        return  method_hints

    def _has_pagination_parameters(self, parameters: List[ParameterSpec]) -> bool:
        param_names = [p.name for p in parameters if p.location == "query"]
        page_params = self._pagination_hints.get("detection_rules", {}).get(
            "query_parameters", {}).get("parameters", ["page", "per_page"])
        return any(pp in param_names for pp in page_params)
    
    def _import_statement_for_type(self, type_obj: Type, extra_names: Optional[List[str]] = None) -> str:
        """
            Build a from-import statement for a given type.
        """
        module_name = type_obj.__module__
        type_name = type_obj.__name__
        if extra_names:
            names_list = [type_name] + extra_names
            names = ", ".join(sorted(names_list))
        else:
            names = type_name
        return f"from {module_name} import {names}"

    def _is_paginated_operation(self, op: OperationSpec) -> bool:
        """
            Determine if an operation returns paginated results.
            
            :returns: True if the operation is paginated
        """
        if op.archetype == "paged-collection":
            return True
        if op.archetype == "collection":
            return False

        # Check if it's a list response
        if op.response_schema_info and op.response_schema_info.get("type") != "list":
            return False
        
        # Check if it has page/per_page parameters
        param_names = [p.name for p in op.parameters]
        page_params = self._pagination_hints.get("detection_rules", {}).get(
            "query_parameters", {}).get("parameters", ["page", "per_page"])
        
        has_page_params = any(pp in param_names for pp in page_params)
        
        return has_page_params
    
    def _load_api_hints(self) -> Dict[str, Any]:
        """
            Load API hints configuration. This is a dictionary keyed by API path
            that provides hints for code generation (e.g. method-name or operationId overrides).
        """
        hints: Dict[str, Any] = {"paths": {}}

        json_file = self._spec_path.parent / "api-hints.json"
        if json_file.exists():
            with open(json_file, "r", encoding="utf-8") as hf:
                loaded = json.load(hf)
            normalized = self._normalize_api_hints(loaded)
            self._merge_api_hints(hints, normalized)

        yaml_file = self._spec_path.parent / "api-hints.yaml"
        if not yaml_file.exists():
            yaml_file = self._spec_path.parent / "api-hints.yml"

        if yaml_file.exists():
            if yaml is None:
                errmsg = "Yaml hints file found but PyYAML is not installed. Install PyYAML to use api-hints.yaml."
                raise RuntimeError(errmsg)
            with open(yaml_file, "r", encoding="utf-8") as hf:
                loaded = yaml.safe_load(hf)
            normalized = self._normalize_api_hints(loaded)
            self._merge_api_hints(hints, normalized)

        return hints

    def _load_openapi_spec(self, spec_path: Path) -> Dict[str, Any]:
        """
            Load an OpenAPI specification file from JSON or YAML.
        """
        suffix = spec_path.suffix.lower()
        if suffix in (".yaml", ".yml"):
            if yaml is None:
                errmsg = "Yaml OpenAPI spec file provided but PyYAML is not installed."
                raise RuntimeError(errmsg)
            with open(spec_path, "r", encoding="utf-8") as sf:
                return yaml.safe_load(sf)
        if suffix == ".json":
            with open(spec_path, "r", encoding="utf-8") as sf:
                return json.load(sf)

        with open(spec_path, "r", encoding="utf-8") as sf:
            raw_content = sf.read()

        try:
            return json.loads(raw_content)
        except json.JSONDecodeError:
            if yaml is None:
                errmsg = "Unable to parse OpenAPI spec as JSON and PyYAML is not installed."
                raise RuntimeError(errmsg)
            return yaml.safe_load(raw_content)

    def _merge_api_hints(self, base: Dict[str, Any], incoming: Dict[str, Any]):
        """
            Merge API hints dictionaries with incoming values overriding base values.

            :param base: Base hints dictionary.
            :param incoming: Incoming hints dictionary.
        """
        base_paths = base.setdefault("paths", {})
        incoming_paths = incoming.get("paths", {})
        for path, methods in incoming_paths.items():
            if path not in base_paths:
                base_paths[path] = methods
                continue
            for method, method_hints in methods.items():
                if method not in base_paths[path]:
                    base_paths[path][method] = method_hints
                elif isinstance(base_paths[path][method], dict) and isinstance(method_hints, dict):
                    base_paths[path][method].update(method_hints)
                else:
                    base_paths[path][method] = method_hints
        return

    def _normalize_api_hints(self, hints: Optional[Dict[str, Any]]) -> Dict[str, Any]:
        """
            Normalize hints to a dictionary with a top-level 'paths' key.

            :param hints: Raw hints dictionary loaded from json/yaml.

            :returns: Normalized hints dictionary.
        """
        normalized: Dict[str, Any] = {"paths": {}}
        if not hints:
            return normalized

        if "paths" in hints:
            paths = hints.get("paths", {})
        else:
            paths = hints

        for path, methods in paths.items():
            if not isinstance(methods, dict):
                continue
            method_map: Dict[str, Any] = {}
            for method, method_hints in methods.items():
                method_key = method.lower()
                method_map[method_key] = method_hints
            normalized["paths"][path] = method_map

        return normalized
    
    def _normalize_archetype(self, archetype: Optional[str]) -> Optional[str]:
        if not archetype:
            return None
        archetype = str(archetype).strip().lower()
        return archetype

    def _order_schema_definitions(self, schemas: List[Tuple[str, TypeSpec]]) -> List[Tuple[str, TypeSpec]]:
        """
            Order schema definitions so dependent types in the same module are defined first.
        """
        schema_by_name: Dict[str, Tuple[str, TypeSpec]] = {}
        dependencies_by_name: Dict[str, set] = {}

        for schema_name, type_spec in schemas:
            schema_by_name[type_spec.name] = (schema_name, type_spec)

        for schema_name, type_spec in schemas:
            dependencies: set = set()
            self._collect_schema_types_from_properties(type_spec.schema, dependencies)
            dependencies.discard(type_spec.name)
            dependencies.intersection_update(schema_by_name.keys())
            dependencies_by_name[type_spec.name] = dependencies

        ordered: List[Tuple[str, TypeSpec]] = []
        pending = sorted(schema_by_name.keys())

        while pending:
            ready = [name for name in pending if not dependencies_by_name[name]]
            if not ready:
                break

            for name in ready:
                pending.remove(name)
                ordered.append(schema_by_name[name])
                for remaining in pending:
                    dependencies_by_name[remaining].discard(name)

        for name in pending:
            ordered.append(schema_by_name[name])

        return ordered

    def _process_spec(self):
        spec = self._spec

        for item in spec.get("tags", []):
            name = item["name"]
            desc = item.get("description", "")
            self._tag_catalog[self._safe_snake(name)] = desc

        path_catalog: Dict[str, dict] = spec["paths"]
        for path_leaf, method_catalog in path_catalog.items():
            path_level_params = method_catalog.get("parameters", [])
            for call_method, op_desc in method_catalog.items():
                if call_method not in SUPPORTED_HTTP_METHODS:
                    continue

                operation_id = op_desc.get("operationId", "")
                method_hints = self._get_api_method_hints(path_leaf, call_method)
                if "operationId" in method_hints:
                    operation_id = method_hints["operationId"]
                tags = op_desc.get("tags", [])
                summary = op_desc.get("summary", "")
                description = op_desc.get("description", "")
                external_docs = op_desc.get("externalDocs")
                responses = op_desc.get("responses", {})
                request_body = op_desc.get("requestBody")

                group_name, method_name = self._derive_group_and_method(operation_id, tags, path_leaf, call_method)

                parameters = self._collect_parameters(
                    path_level_params, op_desc.get("parameters", [])
                )
                
                # Extract response schema information
                response_schema_info = self._extract_response_schema_info(responses)

                archetype = self._detect_api_archetype(
                    path_leaf, call_method, operation_id, op_desc, parameters, response_schema_info
                )

                op = OperationSpec(
                    path=path_leaf,
                    http_method=call_method.upper(),
                    group=group_name,
                    operation_id=operation_id,
                    method_name=method_name,
                    summary=summary,
                    description=description,
                    parameters=parameters,
                    request_body=request_body,
                    responses=responses,
                    external_docs=external_docs,
                    response_schema_info=response_schema_info,
                    archetype=archetype,
                )
                self._groups.setdefault(group_name, []).append(op)
        return

    def _resolve_ref(self, ref_path: str):
        if not ref_path.startswith("#/"):
            errmsg = f"Unsupported reference format '{ref_path}'."
            raise ValueError(errmsg)

        segments = ref_path.lstrip("#/").split("/")
        obj: Any = self._spec
        for segment in segments:
            obj = obj[segment]
        return obj

    def _safe_snake(self, name: str) -> str:
        snake = re.sub(r"[^0-9a-zA-Z]+", "_", name).strip("_").lower()
        if snake == "" or snake[0].isdigit() or keyword.iskeyword(snake):
            snake = f"op_{snake}"
        return snake

    def _safe_pascal(self, name: str) -> str:
        parts = re.split(r"[^0-9a-zA-Z]+", name)
        pascal = "".join([p.capitalize() for p in parts if p])
        if pascal == "":
            pascal = "Generated"
        if pascal[0].isdigit():
            pascal = f"Op{pascal}"
        return pascal

    def _schema_can_generate_class(self, schema: Dict[str, Any]) -> bool:
        """
            Determine if a schema can generate a SchemaObject class.
        """
        if "properties" not in schema:
            return False

        properties = schema.get("properties", {})
        if not properties:
            return False

        attr_names = [self._safe_snake(fname) for fname in properties.keys()]
        if len(attr_names) != len(set(attr_names)):
            return False

        return True

    def _schema_to_type(self, schema: Dict[str, Any], nullable: bool = False, refs_seen: Optional[set] = None, use_forward_refs: bool = False) -> str:
        """
            Convert an OpenAPI schema to a Python type annotation.
        """
        if refs_seen is None:
            refs_seen = set()

        if "$ref" in schema:
            ref_path = schema["$ref"]
            # Extract the type name from the reference
            schema_name = ref_path.split("/")[-1]
            type_name = self._safe_pascal(schema_name)

            if schema_name in refs_seen:
                return "Any"

            refs_seen.add(schema_name)

            type_spec = self._schema_types.get(schema_name)
            if type_spec:
                if self._schema_can_generate_class(type_spec.schema):
                    type_expr = f"\"{type_name}\"" if use_forward_refs else type_name
                    if nullable or schema.get("nullable", False):
                        return f"Optional[{type_expr}]"
                    return type_expr
                return self._schema_to_type(type_spec.schema, nullable, refs_seen, use_forward_refs)

            if nullable or schema.get("nullable", False):
                return "Optional[Any]"
            return "Any"

        # Check for nullable at the schema level
        is_nullable = nullable or schema.get("nullable", False)
        
        # Handle oneOf/anyOf (use Union)
        if "oneOf" in schema or "anyOf" in schema:
            variants = schema.get("oneOf") or schema.get("anyOf") or []
            types = [self._schema_to_type(v, False, refs_seen, use_forward_refs) for v in variants]
            union_type = f"Union[{', '.join(types)}]"
            if is_nullable:
                return f"Optional[{union_type}]"
            return union_type
        
        schema_type = schema.get("type", "any")
        
        if schema_type == "integer":
            base_type = "int"
        elif schema_type == "number":
            base_type = "float"
        elif schema_type == "boolean":
            base_type = "bool"
        elif schema_type == "array":
            item_schema = schema.get("items", {})
            item_type = self._schema_to_type(item_schema, refs_seen=refs_seen, use_forward_refs=use_forward_refs)
            base_type = f"List[{item_type}]"
        elif schema_type == "object":
            base_type = "Dict[str, Any]"
        else:
            base_type = "str"
        
        if is_nullable:
            return f"Optional[{base_type}]"
        return base_type

    def _write_file(self, path: Path, content: str):
        path.write_text(content, encoding="utf-8")
        return

    def _format_import_sections(self, sections: List[List[str]]) -> List[str]:
        """
            Format import sections in order and sort each section alphabetically.
        """
        lines: List[str] = []
        for section in sections:
            if not section:
                continue
            lines.extend(sorted(section))
            lines.append("")
        if lines:
            lines.pop()
        return lines

    def _write_schemas_init(self, schemas_dir: Path):
        """
            Generate an empty __init__.py for schemas to avoid eager schema imports.
        """
        init_file = schemas_dir / "__init__.py"
        self._write_file(init_file, "")
        return

    def _write_simple_init(self, target_dir: Path):
        init_file = target_dir / "__init__.py"
        if init_file.exists():
            return
        init_file.write_text("", encoding="utf-8")
        return


def rest_client_generator_main():
    """
        Entry point used to generate REST client code from the OpenAPI specification.
    """
    parser = argparse.ArgumentParser(description="Generate REST client code from an OpenAPI specification.")
    parser.add_argument("--client-root", required=True, help="Root directory where the generated client package (public) resides.")
    parser.add_argument("--client-classname", default="GithubRestClient", help="Class name to use for the generated root client.")
    parser.add_argument("--specfile", required=True, help="Path to the OpenAPI specification JSON or YAML file.")

    args = parser.parse_args()

    # Use this package's own RestClientGenerator. The previous import of
    # ccai.github.rest.generation.githubrestclientgenerator resolved nowhere (the
    # base package must not depend on a specific client package); the local
    # generator has the same constructor and is the correct foundation entry point.
    generator = RestClientGenerator(
        openapi_spec_file=args.specfile,
        clients_root=args.client_root,
        client_class_name=args.client_classname
    )
    generator.generate()
    return


if __name__ == "__main__":
    rest_client_generator_main()
